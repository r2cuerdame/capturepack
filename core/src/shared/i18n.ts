// Shared i18n layer (GOAL "Internationalization (9+ languages)"): every user-
// visible UI string in the app goes through makeT(); no hardcoded UI strings
// outside the dictionaries below and the static English source text in the
// renderer html files (which is re-applied from these dictionaries at load via
// data-i18n attributes).
//
// Deliberate English-only surfaces (NOT routed through this layer):
// - MCP tool names/descriptions/responses (LLM-facing API surface, mcp/tools.ts)
// - the save toast's "Copy Prompt" text (FIXED CONTRACT in saveToast.ts)
// - console/log output and internal IPC guard errors the user never sees
// - pack document PROSE (packdocs.ts/report.ts): template HEADINGS and short
//   labels are localized via the pack.* keys; explanatory prose stays English
//   so the documents remain canonical for AI readers
// - the user's own title/note text is NEVER translated
//
// Adding a language = adding one dictionary entry; a missing key or missing
// translation falls back to English at runtime (and the Record<I18nKey,string>
// typing keeps every shipped dictionary complete at compile time).

export const SUPPORTED_LANGUAGES = ['en', 'ko', 'ja', 'zh', 'es', 'fr', 'de', 'pt', 'ru'] as const

export type Language = (typeof SUPPORTED_LANGUAGES)[number]

/** Native-script names for the language picker (language-invariant on purpose). */
export const LANGUAGE_NATIVE_NAMES: Record<Language, string> = {
  en: 'English',
  ko: '한국어',
  ja: '日本語',
  zh: '中文',
  es: 'Español',
  fr: 'Français',
  de: 'Deutsch',
  pt: 'Português',
  ru: 'Русский',
}

export function isSupportedLanguage(value: string): value is Language {
  return (SUPPORTED_LANGUAGES as readonly string[]).includes(value)
}

/**
 * Resolves the settings.language value ("system" or a language code) to a
 * supported language: an explicit supported code wins; anything else (i.e.
 * "system") derives from the app locale's two-letter code; fallback English.
 */
export function resolveLanguage(setting: string, appLocale: string): Language {
  if (isSupportedLanguage(setting)) return setting
  const two = appLocale.slice(0, 2).toLowerCase()
  return isSupportedLanguage(two) ? two : 'en'
}

