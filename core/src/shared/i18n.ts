export const DICT: Record<Language, Record<I18nKey, string>> = {
  en: EN,
  ko: KO,
  ja: JA,
  zh: ZH,
  es: ES,
  fr: FR,
  de: DE,
  pt: PT,
  ru: RU,
}

export type TranslateVars = Record<string, string | number>
export type TranslateFn = (key: I18nKey, vars?: TranslateVars) => string

function interpolate(template: string, vars: TranslateVars): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name]
    return value === undefined ? match : String(value)
  })
}

/**
 * Returns t(key, vars?) for `lang`. An unsupported lang behaves as English;
 * a missing key or missing translation falls back to the English string, and
 * an entirely unknown key falls back to the key itself (never throws).
 */
export function makeT(lang: string): TranslateFn {
  const dict: Partial<Record<I18nKey, string>> = isSupportedLanguage(lang) ? DICT[lang] : EN
  return (key, vars) => {
    const template = dict[key] ?? EN[key] ?? key
    return vars === undefined ? template : interpolate(template, vars)
  }
}

// ---------------------------------------------------------------------------
// Renderer helper: re-applies the active language over the static English
// source text in the html files. Elements opt in with:
//   data-i18n             -> textContent
//   data-i18n-title       -> title attribute (tooltips)
//   data-i18n-placeholder -> placeholder attribute (inputs)
//   data-i18n-aria-label  -> aria-label attribute
// (Renderer windows only — main never calls this.)
// ---------------------------------------------------------------------------

export function applyDomI18n(t: TranslateFn, root: ParentNode = document): void {
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = node.dataset['i18n']
    if (key !== undefined) node.textContent = t(key as I18nKey)
  }
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const key = node.dataset['i18nTitle']
    if (key !== undefined) node.title = t(key as I18nKey)
  }
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]')) {
    const key = node.dataset['i18nPlaceholder']
    if (key !== undefined) node.setAttribute('placeholder', t(key as I18nKey))
  }
  for (const node of root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]')) {
    const key = node.dataset['i18nAriaLabel']
    if (key !== undefined) node.setAttribute('aria-label', t(key as I18nKey))
  }
}
