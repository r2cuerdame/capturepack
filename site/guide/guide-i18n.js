  var SUPPORTED = ['en', 'ko', 'ja', 'zh', 'es', 'fr', 'de', 'pt', 'ru']

  function detect() {
    var saved = null
    try { saved = localStorage.getItem('cp_lang') } catch (e) {}
    if (saved && SUPPORTED.indexOf(saved) >= 0) return saved
    var nav = (navigator.language || 'en').toLowerCase().slice(0, 2)
    return SUPPORTED.indexOf(nav) >= 0 ? nav : 'en'
  }

  function apply(lang) {
    // English has no dictionary: it is the markup's own text, so switching back
    // to it means reloading rather than re-applying a copy that could drift.
    var dict = DICT[lang]
    if (dict) {
      var nodes = document.querySelectorAll('[data-i18n]')
      for (var i = 0; i < nodes.length; i++) {
        var key = nodes[i].getAttribute('data-i18n')
        if (dict[key]) nodes[i].innerHTML = dict[key]
      }
    }
    document.documentElement.lang = lang
    try { localStorage.setItem('cp_lang', lang) } catch (e) {}
  }

  var sel = document.getElementById('langSel')
  var lang = detect()
  sel.value = lang
  if (lang !== 'en') apply(lang)
  sel.addEventListener('change', function () {
    var next = sel.value
    try { localStorage.setItem('cp_lang', next) } catch (e) {}
    if (next === 'en') location.reload()
    else apply(next)
  })
